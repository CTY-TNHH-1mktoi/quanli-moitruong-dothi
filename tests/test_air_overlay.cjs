'use strict';
const assert = require('node:assert/strict');
const {colorFor, sampleGrid} = require('../static/air-overlay.js');
const grid = {ViDo: [20, 21], KinhDo: [105, 106], BuocLuoiDo: 1, AQI: [[0, 100], [200, 200]]};
assert.equal(sampleGrid(grid, 20.5, 105.5), 125);
assert.equal(sampleGrid(grid, 20, 105), 0);
assert.equal(sampleGrid(grid, 21, 106), 200);
assert.equal(sampleGrid(grid, 19, 105), null);
assert.equal(sampleGrid(grid, 20, 107), null);
const incomplete = {...grid, AQI: [[0, 100], [200, null]]};
assert.equal(sampleGrid(incomplete, 20.5, 105.5), null);
assert.equal(sampleGrid(incomplete, 20, 105), 0);
assert.equal(colorFor(null), null);
assert.equal(colorFor(NaN), null);
assert.equal(colorFor(-1), null);
assert.deepEqual(colorFor(0), [0, 228, 0]);
assert.deepEqual(colorFor(200), [255, 0, 0]);
assert.deepEqual(colorFor(600), colorFor(500));
console.log('13 AQI interpolation/color assertions passed; missing data remains transparent.');
